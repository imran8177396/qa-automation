import type { AssignedScenario, CoverageReport, CoverageRecord } from './types';

function cell(value: string | number | boolean | null | undefined): string {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function table(headers: string[], rows: Array<Array<string | number>>): string {
  const head = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((row) => `| ${row.map((value) => cell(value)).join(' | ')} |`).join('\n');
  return `${head}\n${sep}\n${body}`;
}

function scenarioSummary(scenarios: AssignedScenario[]): string {
  return scenarios.map((scenario) => `${scenario.id} (${scenario.disposition})`).join(', ');
}

function recordFor(report: CoverageReport, id: string): CoverageRecord | undefined {
  return report.records.find((row) => row.id === id);
}

function formatPercent(value: number): string {
  return `${value}%`;
}

export function renderTestInventory(report: CoverageReport): string {
  const lines = [
    '# Test Inventory',
    '',
    'Generated by `npm run coverage`. Do not edit by hand — regenerate after discovery or test execution.',
    '',
    `- Generated at: ${report.generatedAt}`,
    `- Discovery seed: ${report.seedUrl ?? 'not available'}`,
    `- Playwright baseURL: ${report.playwrightBaseUrl}`,
    '',
    'Every discovered, configured, or capability item is listed. Nothing is silently omitted.',
    'Status is TESTED / FAILED / BLOCKED / SKIPPED / NOT APPLICABLE / UNTESTABLE / UNCOVERED.',
    'Coverage is tested ÷ testable. A FAILED item still counts as covered.',
    '',
  ];

  const kinds = [...new Set(report.items.map((item) => item.kind))];
  for (const kind of kinds) {
    const rows = report.items.filter((item) => item.kind === kind);
    lines.push(`## ${kind} (${rows.length})`, '');
    lines.push(
      table(
        ['ID', 'Page', 'Element', 'Type', 'Status', 'Reason', 'Recommended test', 'Scenarios'],
        rows.map((item) => {
          const record = recordFor(report, item.id);
          return [
            item.id,
            record?.page ?? item.page ?? item.route ?? item.source,
            record?.element ?? item.name,
            record?.type ?? item.elementType ?? item.kind,
            record?.status ?? 'UNCOVERED',
            record?.reason ?? '',
            record?.recommendedTest ?? '',
            scenarioSummary(item.applicableScenarios),
          ];
        })
      ),
      ''
    );
  }

  return `${lines.join('\n')}\n`;
}

export function renderCoverageMatrix(report: CoverageReport): string {
  const t = report.totals;
  const lines = [
    '# Coverage Matrix',
    '',
    'Generated by `npm run coverage`. Coverage is **tested ÷ testable discovered items**. Pass rate is reported separately and is never used as coverage.',
    '',
    `- Generated at: ${report.generatedAt}`,
    `- Discovery seed: ${report.seedUrl ?? 'not available'}`,
    `- Playwright baseURL: ${report.playwrightBaseUrl}`,
    '',
    '## Headline',
    '',
    table(
      ['Metric', 'Value'],
      [
        ['Discovered items (from discovery inventories)', t.discoveredItems],
        ['Testable items (have ≥1 executable scenario)', t.testableItems],
        ['Covered items (TESTED + FAILED)', t.testedItems],
        ['UNCOVERED (testable, no evidence)', t.uncoveredItems],
        ['Item coverage (covered ÷ testable)', formatPercent(t.itemCoveragePercent)],
        ['Executable scenarios', t.executableScenarios],
        ['Scenarios actually tested', t.testedScenarios],
        ['Scenario coverage (tested ÷ executable)', formatPercent(t.scenarioCoveragePercent)],
        ['Executions passed', t.passedExecutions],
        ['Executions failed', t.failedExecutions],
        ['Pass rate (not coverage)', t.passRatePercent == null ? 'no executions' : formatPercent(t.passRatePercent)],
      ]
    ),
    '',
    `**Item coverage = ${t.testedItems} / ${t.testableItems} = ${formatPercent(t.itemCoveragePercent)}**`,
    '',
    'Passing tests do not imply 100% coverage. An item is covered only when execution evidence targets that item. FAILED still counts as covered.',
    '',
    '## Coverage formula',
    '',
    report.formula.testableItemDefinition,
    '',
    report.formula.coverageDefinition,
    '',
    `**Warning:** ${report.formula.warning}`,
    '',
    table(
      ['Figure', 'Testable', 'Covered', 'Coverage'],
      [
        [
          report.formula.figures.elementCoverage.label,
          report.formula.figures.elementCoverage.testable,
          report.formula.figures.elementCoverage.covered,
          formatPercent(report.formula.figures.elementCoverage.coveragePercent),
        ],
        [
          report.formula.figures.functionalAreaCoverage.label,
          report.formula.figures.functionalAreaCoverage.testable,
          report.formula.figures.functionalAreaCoverage.covered,
          formatPercent(report.formula.figures.functionalAreaCoverage.coveragePercent),
        ],
      ]
    ),
    '',
    table(
      ['Dimension', 'Raw', 'Unique (after URL dedupe)', 'Testable', 'Covered', 'Excluded', 'Coverage'],
      (['pages', 'interactiveElements', 'endpoints', 'workflows'] as const).map((key) => {
        const row = report.formula.contributions[key];
        return [
          key,
          row.discoveredRaw,
          row.discoveredUnique,
          row.testable,
          row.covered,
          row.excluded.length,
          formatPercent(row.coveragePercent),
        ];
      })
    ),
    '',
    '## Status counts (every item)',
    '',
    table(
      ['Status', 'Count'],
      Object.entries(t.byStatus).map(([label, count]) => [label, count])
    ),
    '',
    '## Advanced dimensions',
    '',
    'Each row is discovered testable items for that dimension — not the number of passing tests.',
    '',
    table(
      ['Dimension', 'Discovered', 'Testable', 'Covered', 'Uncovered', 'Coverage', 'TESTED', 'FAILED', 'BLOCKED', 'SKIPPED', 'N/A', 'UNTESTABLE'],
      report.dimensions.map((row) => [
        row.label,
        row.discovered,
        row.testable,
        row.covered,
        row.uncovered,
        formatPercent(row.coveragePercent),
        row.byStatus.TESTED,
        row.byStatus.FAILED,
        row.byStatus.BLOCKED,
        row.byStatus.SKIPPED,
        row.byStatus['NOT APPLICABLE'],
        row.byStatus.UNTESTABLE,
      ])
    ),
    '',
    '## By kind',
    '',
    table(
      ['Kind', 'Items', 'Testable', 'Tested', 'Uncovered', 'Item coverage', 'Scenario coverage'],
      report.byKind.map((row) => [
        row.kind,
        row.discovered,
        row.testable,
        row.tested,
        row.uncovered,
        formatPercent(row.itemCoveragePercent),
        formatPercent(row.scenarioCoveragePercent),
      ])
    ),
    '',
  ];

  if (report.targetMismatch) {
    lines.push(
      '## Target mismatch',
      '',
      `Discovery seed is \`${report.seedUrl}\` and \`qa.config.json\` Playwright baseURL is \`${report.playwrightBaseUrl}\`. Coverage still counts only executions whose URL/locator evidence matches the discovered host — not every passing test.`,
      ''
    );
  }

  if (report.notes.length > 0) {
    lines.push('## Notes', '');
    for (const note of report.notes) lines.push(`- ${note}`);
    lines.push('');
  }

  return `${lines.join('\n')}\n`;
}

export function renderUncovered(report: CoverageReport): string {
  const listed = report.records.filter((row) => row.status !== 'TESTED');
  const lines = [
    '# Uncovered Test Items',
    '',
    'Generated by `npm run coverage`. Every item that is not TESTED is listed with page, element, type, reason, recommended test, and status. Nothing is silently omitted.',
    '',
    `- Generated at: ${report.generatedAt}`,
    `- Items not TESTED: ${listed.length} (UNCOVERED ${report.totals.uncoveredItems}; others are FAILED / BLOCKED / SKIPPED / NOT APPLICABLE / UNTESTABLE)`,
    '',
  ];

  if (listed.length === 0) {
    lines.push('Every inventory item is TESTED. This can only happen when every item has passing execution evidence.');
    lines.push('');
    return `${lines.join('\n')}\n`;
  }

  const statuses = [...new Set(listed.map((row) => row.status))];
  for (const status of statuses) {
    const rows = listed.filter((row) => row.status === status);
    lines.push(`## ${status} (${rows.length})`, '');
    lines.push(
      table(
        ['ID', 'Page', 'Element', 'Type', 'Status', 'Reason', 'Recommended test'],
        rows.map((row) => [row.id, row.page, row.element, row.type, row.status, row.reason, row.recommendedTest])
      ),
      ''
    );
  }

  return `${lines.join('\n')}\n`;
}
